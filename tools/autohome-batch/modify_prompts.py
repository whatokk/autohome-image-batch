def rebuild(path, dst):
    lines = open(path, encoding='utf-8').read().split('\n')
    out = []
    n = 0
    changed = 0
    for line in lines:
        if not line.strip() or line.startswith('#') or '\t' not in line:
            out.append(line)
            continue
        ref, _, prompt = line.partition('\t')
        idx = prompt.find('新场景：')
        if idx == -1:
            out.append(line)
            continue
        n += 1
        head = prompt[:idx]
        tail = TAIL_TPL.format(**DATA[n])
        out.append(ref + '\t' + head + tail)
        changed += 1
    open(dst, 'w', encoding='utf-8', newline='').write('\n'.join(out))
    print('%s -> 改写 %d 条' % (os.path.basename(path), changed))


